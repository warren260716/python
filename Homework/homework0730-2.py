# 讓使用者輸入身高（公分）和體重（公斤）
身高cm = float(input("請輸入您的身高（cm）："))
體重kg = float(input("請輸入您的體重（kg）："))

# 檢查輸入是否合理
if 身高cm <= 0 or 體重kg <= 0:
      print("身高和體重必須為正數！")      

# 將身高轉換為公尺
身高m = 身高cm / 100

# 計算 BMI：體重（kg） / 身高（m）^2
bmi = 體重kg / (身高m ** 2)

# 根據 BMI 值判斷分級
if bmi < 18.5:
      判斷 = "體重過輕"
elif 18.5 <= bmi < 24:
      判斷 = "正常範圍"
elif 24 <= bmi < 27:
      判斷 = "過重"
elif 27 <= bmi < 30:
      判斷 = "輕度肥胖"
elif 30 <= bmi < 35:
      判斷 = "中度肥胖"
else:
      判斷 = "重度肥胖"
        
# 輸出結果（顯示至小數點後第二位）
print(f"BMI值為{bmi:.2f}，屬{判斷}。")