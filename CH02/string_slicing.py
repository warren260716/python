flavor = "fig pie"
print(flavor[0:3]) #從0開始往後數3個
print(flavor[3:7]) #從3開始往後數7個
print(flavor[3:]) #從3開始掃到最後面
print(flavor[:]) #從頭掃到尾
print(flavor[:14])  #從頭開始掃到第14個 
print(flavor[13:15]) #從第13個往後數到第15個
print(flavor[-7:-4]) #從-7開始到-4
print(flavor[-7:0]) #從-7到0，因為這兩個是同一個位置，會得到空白
print(flavor[-7:]) #從-7開始掃到底
print(flavor[-3:]) #從-3開始掃到底
print(flavor[-10:]) 
