print('%f'%12345.67) #小數點位數預設六位
print('%f'%-12.345) #小數點位數預設六位
print('%.2f'%12.345) #設小數位數2位，第3位四捨五入
print('%8.2f'%-12.3456) #設總寬度8位，小數2位
print('%3.1f'%123.45) #設寬度3且小數1位，寬度不足時全部顯示
print('%8.0f'%-1234.56) #設小數位數0位，第1位四捨五入
print('%8.0f'%1234.56) #設小數位數0位，第1位四捨五入
print('%E'%1234567.89) #科學記號寬度不足時會四捨五入
print('%e'%123.4) #科學記號小數部分6位，小數位數不足補0
print('%10.2e'%12345.6) #設總寬度10，小數位數2位
print('%10.2E'%0.000123456) #設總寬度10，小數2位